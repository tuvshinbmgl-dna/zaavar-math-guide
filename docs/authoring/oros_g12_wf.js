const bundleSchema = (withMastery, withNotes) => ({
  type: 'object', additionalProperties: false,
  required: ['lesson', 'level_questions', 'mastery'].concat(withNotes ? ['notes'] : []),
  properties: {
    lesson: LESSON,
    level_questions: { type: 'array', minItems: 10, maxItems: 10, items: LEVELQ },
    mastery: withMastery ? MASTERY_OBJ : { type: 'null' },
    ...(withNotes ? { notes: { type: 'string' } } : {}),
  },
})

phase('Author')
log(`Орос хэл ${GRADE}: ${SPECS.length} тема — зохиох + дүрмийн шалгалт`)
const results = await pipeline(
  SPECS,
  (s) => agent(authorPrompt(s), { label: `author:${s.skill}`, phase: 'Author', schema: bundleSchema(s.mastery, false) })
    .then(b => ({ spec: s, bundle: b })),
  ({ spec, bundle }) => {
    if (!bundle) return null
    return agent(verifyPrompt(spec, bundle), { label: `verify:${spec.skill}`, phase: 'Verify', schema: bundleSchema(spec.mastery, true) })
      .then(v => ({ spec, final: v || bundle, notes: v?.notes || '(verify failed → author kept)' }))
  }
)

const ok = results.filter(Boolean)
const withMastery = ok.filter(r => r.final.mastery).length
log(`Authored+verified ${ok.length}/${SPECS.length} темы · mastery ${withMastery}/${SPECS.filter(s => s.mastery).length}`)
return {
  subject: 'oros',
  grade: GRADE,
  topics: ok.map(r => ({ skill: r.spec.skill, id: r.spec.id, notes: r.notes, bundle: {
    lesson: r.final.lesson, level_questions: r.final.level_questions, mastery: r.final.mastery,
  } })),
}
